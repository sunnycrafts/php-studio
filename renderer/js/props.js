/* PHP Studio — properties panel: Figma/Webflow-style inspector.
 * Style/text/attribute edits are applied to the live preview DOM instantly
 * (no reload) and written back to the PHP source in the background.
 * Structural edits (add/delete/duplicate) do a full preview refresh. */
'use strict';

window.Props = (function () {

  function clear() {
    S.selected = null;
    $('#propsEmpty').style.display = '';
    $('#propsContent').style.display = 'none';
    $('#propsContent').innerHTML = '';
  }

  /* Debounced writers */
  let liveTimer = 0;
  function applyLive(fn, patchMsg) {
    // patch the live DOM immediately…
    if (patchMsg) Preview.patch(patchMsg);
    // …and debounce the source write-back + map refresh
    clearTimeout(liveTimer);
    liveTimer = setTimeout(() => {
      const ok = fn();
      if (ok === false) { toast('warn', 'Could not apply that change', 'This part of the page is generated by PHP.'); Preview.update(true); return; }
      Preview.updateSilent();
    }, 300);
  }
  let structTimer = 0;
  function applyStructural(fn) {
    clearTimeout(structTimer);
    structTimer = setTimeout(() => {
      const ok = fn();
      if (ok !== false) Preview.update(true);
    }, 0);
  }

  /* ── UI builders ────────────────────────────────────── */
  function accordion(title, open) {
    const acc = document.createElement('div');
    acc.className = 'acc' + (open ? ' open' : '');
    acc.innerHTML = `<div class="acc-head"><span></span><span class="chev">${ICONS.chevron}</span></div><div class="acc-body"></div>`;
    $('.acc-head span', acc).textContent = title;
    $('.acc-head', acc).addEventListener('click', () => acc.classList.toggle('open'));
    return acc;
  }
  function row(label, control) {
    const r = document.createElement('div');
    r.className = 'prow';
    const l = document.createElement('label');
    l.textContent = label;
    r.appendChild(l);
    r.appendChild(control);
    return r;
  }
  function textInput(value, onchange, placeholder) {
    const i = document.createElement('input');
    i.type = 'text'; i.spellcheck = false;
    i.value = value || '';
    if (placeholder) i.placeholder = placeholder;
    i.addEventListener('change', () => onchange(i.value));
    return i;
  }
  function selectInput(options, value, onchange) {
    const s = document.createElement('select');
    for (const o of options) {
      const op = document.createElement('option');
      op.value = o; op.textContent = o || '(default)';
      s.appendChild(op);
    }
    s.value = options.includes(value) ? value : options[0];
    s.addEventListener('change', () => onchange(s.value));
    return s;
  }

  function toHex(cssColor) {
    if (!cssColor) return '#000000';
    if (cssColor.startsWith('#')) return cssColor.length === 4
      ? '#' + [...cssColor.slice(1)].map((c) => c + c).join('') : cssColor.slice(0, 7);
    const m = /rgba?\(\s*(\d+)[,\s]+(\d+)[,\s]+(\d+)/.exec(cssColor);
    if (!m) return '#000000';
    return '#' + [m[1], m[2], m[3]].map((x) => (+x).toString(16).padStart(2, '0')).join('');
  }
  function colorInput(cssColor, onchange) {
    const wrap = document.createElement('div');
    wrap.style.cssText = 'display:flex;gap:6px;flex:1;align-items:center';
    const c = document.createElement('input');
    c.type = 'color';
    c.value = toHex(cssColor);
    const t = document.createElement('input');
    t.type = 'text'; t.spellcheck = false; t.style.flex = '1';
    t.value = cssColor || '';
    c.addEventListener('input', () => { t.value = c.value; onchange(c.value); });
    t.addEventListener('change', () => { c.value = toHex(t.value); onchange(t.value); });
    wrap.append(c, t);
    return wrap;
  }
  function sliderInput(value, min, max, unit, onchange) {
    const wrap = document.createElement('div');
    wrap.style.cssText = 'display:flex;gap:8px;flex:1;align-items:center';
    const r = document.createElement('input');
    r.type = 'range'; r.min = min; r.max = max; r.step = 1;
    r.value = parseFloat(value) || 0;
    const t = document.createElement('input');
    t.type = 'text'; t.style.width = '64px'; t.spellcheck = false;
    t.value = value || '';
    r.addEventListener('input', () => { t.value = r.value + unit; onchange(r.value + unit); });
    t.addEventListener('change', () => { r.value = parseFloat(t.value) || 0; onchange(t.value); });
    wrap.append(r, t);
    return wrap;
  }

  /* ── main render ────────────────────────────────────── */
  function show(el) {
    S.selected = el;
    $('#propsEmpty').style.display = 'none';
    const box = $('#propsContent');
    box.style.display = '';
    box.innerHTML = '';
    const id = el.id;
    const srcNode = S.map[id];

    const desc = ChangeLog.describe(el);
    const filePath = S.active ? S.active.path : null;

    /* live style edit: instant DOM patch + background write-back */
    const style = (prop, v) => {
      ChangeLog.note(filePath, `style:${id}:${prop}`,
        v === '' ? `Removed the ${ChangeLog.propLabel(prop)} override on ${desc}`
                 : `Changed the ${ChangeLog.propLabel(prop)} of ${desc} to ${v}`);
      applyLive(
        () => Edits.setStyle(id, prop, v),
        { psCmd: 'patch', id, kind: 'style', prop, value: v === '' ? null : v },
      );
    };
    const attr = (name, v) => {
      const what =
        name === 'src' ? `Swapped the picture in ${desc}` :
        name === 'href' ? `Changed where ${desc} points to (${v})` :
        name === 'alt' ? `Changed the description of ${desc}` :
        `Changed ${name} of ${desc}`;
      ChangeLog.note(filePath, `attr:${id}:${name}`, what);
      applyLive(
        () => Edits.setAttr(id, name, v === '' ? null : v),
        { psCmd: 'patch', id, kind: 'attr', name, value: v === '' ? null : v },
      );
    };

    function boxInputs(prefix) {
      const grid = document.createElement('div');
      grid.className = 'prow-grid4';
      for (const side of ['top', 'right', 'bottom', 'left']) {
        const cell = document.createElement('div');
        cell.className = 'pg-cell';
        const lab = document.createElement('span');
        lab.textContent = side[0].toUpperCase();
        lab.title = side;
        const i = document.createElement('input');
        i.type = 'text'; i.spellcheck = false;
        i.value = el.styles[`${prefix}-${side}`] || '';
        i.addEventListener('change', () => style(`${prefix}-${side}`, i.value));
        cell.append(lab, i);
        grid.appendChild(cell);
      }
      return grid;
    }

    /* badge */
    const badge = document.createElement('div');
    badge.className = 'el-badge';
    badge.innerHTML = `<b></b><span class="dim"></span>`;
    $('b', badge).textContent = '<' + el.tag + '>';
    $('.dim', badge).textContent = (el.attrs.class ? '.' + el.attrs.class.split(/\s+/)[0] : '') + (el.attrs.id ? ' #' + el.attrs.id : '');
    box.appendChild(badge);

    /* safe-editing indicator: one clear signal for what can be changed here */
    {
      const innerPhp = !srcNode || (srcNode.closeStart >= 0 && srcNode.innerPhp);
      const attrPhp = !srcNode || srcNode.attrPhp;
      let level, label, why;
      if (!srcNode) {
        level = 'red'; label = 'Generated by PHP';
        why = 'This part is produced by code when the page loads — change it in Code view (Advanced).';
      } else if (!innerPhp && !attrPhp) {
        level = 'green'; label = 'Fully editable';
        why = 'Words, pictures, colors and spacing — change anything here safely.';
      } else if (innerPhp && attrPhp) {
        level = 'red'; label = 'Generated by PHP';
        why = 'The words and settings here come from code. Colors and spacing can still be changed.';
      } else if (innerPhp) {
        level = 'amber'; label = 'Partly editable';
        why = 'The words inside come from code, but looks (colors, size, spacing) can be changed.';
      } else {
        level = 'amber'; label = 'Partly editable';
        why = 'Some settings here are filled in by code; everything else can be changed.';
      }
      const pill = document.createElement('div');
      pill.className = 'edit-pill ' + level;
      pill.innerHTML = `<span class="ep-dot"></span><b></b><span class="ep-why"></span>`;
      $('b', pill).textContent = label;
      $('.ep-why', pill).textContent = why;
      box.appendChild(pill);
      Preview.patch({ psCmd: 'selcolor', level });
    }

    /* quick actions */
    const actions = document.createElement('div');
    actions.className = 'el-actions';
    const mkAct = (icon, title, fn) => {
      const b = document.createElement('button');
      b.className = 'icon-btn sm'; b.title = title; b.innerHTML = ICONS[icon];
      b.addEventListener('click', fn);
      actions.appendChild(b);
    };
    mkAct('code', 'Show in code', () => {
      if (!srcNode) return;
      if (S.view === 'design') setView('split');
      Editor.flashRange(srcNode.openStart, srcNode.closeEnd >= 0 ? srcNode.closeEnd : srcNode.openEnd);
    });
    mkAct('duplicate', 'Duplicate element', () => applyStructural(() => {
      const ok = Edits.duplicateElement(id);
      if (ok) { toast('ok', 'Duplicated', '', 1400); ChangeLog.note(filePath, 'dup:' + Date.now(), `Duplicated ${desc}`); }
      return ok;
    }));
    mkAct('copy', 'Copy HTML', () => { studio.copyToClipboard(Edits.copyElementSource(id)); toast('ok', 'HTML copied', '', 1400); });
    mkAct('trash', 'Delete element', async () => {
      if (await confirmDialog('Delete element', `Remove <b>&lt;${el.tag}&gt;</b> from the page?`, 'Delete')) {
        applyStructural(() => {
          const ok = Edits.removeElement(id);
          if (ok) { clear(); toast('ok', 'Element deleted', '', 1600); ChangeLog.note(filePath, 'del:' + Date.now(), `Deleted ${desc}`); }
          return ok;
        });
      }
    });
    box.appendChild(actions);

    /* ── Text ── */
    const VOID = ['img', 'br', 'hr', 'input', 'source', 'track', 'wbr', 'area', 'col', 'embed'];
    if (Edits.canEditText(id) && !VOID.includes(el.tag)) {
      const acc = accordion('Text', true);
      const body = $('.acc-body', acc);
      const ta = document.createElement('textarea');
      const inner = Edits.getInnerSource(id) || '';
      ta.rows = Math.min(7, Math.max(2, Math.ceil(inner.length / 40)));
      ta.value = inner;
      ta.addEventListener('input', () => {
        ChangeLog.note(filePath, `text:${id}`, `Changed the words in ${desc}`);
        applyLive(
          () => Edits.setText(id, ta.value),
          { psCmd: 'patch', id, kind: 'html', value: ta.value },
        );
      });
      body.appendChild(ta);
      if (el.hasElementChild) {
        const hint = document.createElement('p');
        hint.className = 'muted';
        hint.style.cssText = 'font-size:11px;margin:6px 2px 0';
        hint.textContent = 'Bits like <em> or <span> are styling tags — keep them around the words they wrap.';
        body.appendChild(hint);
      }
      box.appendChild(acc);
    }

    /* ── Typography ── */
    {
      const acc = accordion('Typography', true);
      const body = $('.acc-body', acc);
      body.appendChild(row('Size', sliderInput(el.styles['font-size'], 8, 96, 'px', (v) => style('font-size', v))));
      body.appendChild(row('Weight', selectInput(['', '300', '400', '500', '600', '700', '800'], normWeight(el.styles['font-weight']), (v) => style('font-weight', v))));
      body.appendChild(row('Color', colorInput(el.styles.color, (v) => style('color', v))));
      body.appendChild(row('Align', selectInput(['', 'left', 'center', 'right', 'justify'], el.styles['text-align'], (v) => style('text-align', v))));
      body.appendChild(row('Transform', selectInput(['', 'none', 'uppercase', 'lowercase', 'capitalize'], el.styles['text-transform'], (v) => style('text-transform', v))));
      body.appendChild(row('Line height', textInput(el.styles['line-height'], (v) => style('line-height', v), 'e.g. 1.6')));
      box.appendChild(acc);
    }

    /* ── Colors & background ── */
    {
      const acc = accordion('Background & Border', false);
      const body = $('.acc-body', acc);
      body.appendChild(row('Background', colorInput(el.styles['background-color'], (v) => style('background-color', v))));
      body.appendChild(row('Radius', sliderInput(el.styles['border-radius'], 0, 60, 'px', (v) => style('border-radius', v))));
      body.appendChild(row('Border', textInput(borderShorthand(el.styles), (v) => style('border', v), 'e.g. 1px solid #ccc')));
      body.appendChild(row('Opacity', sliderInput(String(Math.round((parseFloat(el.styles.opacity) || 1) * 100)), 0, 100, '%', (v) => style('opacity', String((parseFloat(v) || 100) / 100)))));
      box.appendChild(acc);
    }

    /* ── Spacing ── */
    {
      const acc = accordion('Spacing', false);
      const body = $('.acc-body', acc);
      const lab1 = document.createElement('div');
      lab1.className = 'muted'; lab1.style.cssText = 'font-size:10.5px;text-transform:uppercase;letter-spacing:.05em;margin-top:6px';
      lab1.textContent = 'Margin';
      body.appendChild(lab1);
      body.appendChild(boxInputs('margin'));
      const lab2 = lab1.cloneNode(); lab2.textContent = 'Padding';
      body.appendChild(lab2);
      body.appendChild(boxInputs('padding'));
      box.appendChild(acc);
    }

    /* ── Layout ── */
    {
      const acc = accordion('Layout', false);
      const body = $('.acc-body', acc);
      const inline = Edits.parseStyle(el.inline);
      body.appendChild(row('Display', selectInput(['', 'block', 'inline-block', 'inline', 'flex', 'inline-flex', 'grid', 'none'], el.styles.display, (v) => style('display', v))));
      body.appendChild(row('Width', textInput(inline.width || '', (v) => style('width', v), 'auto')));
      body.appendChild(row('Max width', textInput(inline['max-width'] || '', (v) => style('max-width', v), 'none')));
      body.appendChild(row('Height', textInput(inline.height || '', (v) => style('height', v), 'auto')));
      if ((el.styles.display || '').includes('flex') || (el.styles.display || '').includes('grid')) {
        body.appendChild(row('Gap', textInput(el.styles.gap, (v) => style('gap', v), 'e.g. 16px')));
        body.appendChild(row('Justify', selectInput(['', 'flex-start', 'center', 'flex-end', 'space-between', 'space-around'], el.styles['justify-content'], (v) => style('justify-content', v))));
        body.appendChild(row('Align', selectInput(['', 'stretch', 'flex-start', 'center', 'flex-end'], el.styles['align-items'], (v) => style('align-items', v))));
      }
      box.appendChild(acc);
    }

    /* ── Attributes ── */
    {
      const acc = accordion('Attributes', false);
      const body = $('.acc-body', acc);
      const editable = ['class', 'id', 'href', 'src', 'alt', 'title', 'target'];
      const relevant = editable.filter((a) => a in el.attrs || (el.tag === 'a' && (a === 'href' || a === 'target')) || (el.tag === 'img' && (a === 'src' || a === 'alt')) || a === 'class' || a === 'id');
      for (const a of relevant) {
        const phpBound = srcNode && srcNode.attrs && srcNode.attrs[a] === null && a in (srcNode.attrs || {});
        const inp = textInput(el.attrs[a] || '', (v) => attr(a, v));
        if (phpBound) { inp.disabled = true; inp.title = 'Value is generated by PHP — edit in Code view'; inp.placeholder = '<?php … ?>'; }
        body.appendChild(row(a, inp));
      }
      box.appendChild(acc);
    }

    /* ── One-click picture replacement ── */
    if (el.tag === 'img') {
      const btn = document.createElement('button');
      btn.className = 'btn primary';
      btn.style.cssText = 'margin:12px 14px;width:calc(100% - 28px)';
      btn.textContent = 'Choose picture…';
      const phpSrc = srcNode && srcNode.attrs && srcNode.attrs.src === null && 'src' in (srcNode.attrs || {});
      if (phpSrc) {
        btn.disabled = true;
        btn.title = 'This picture is set by PHP — it has to be changed on the website itself.';
      }
      btn.addEventListener('click', async () => {
        const rel = await studio.pickImage(S.project);
        if (rel) {
          attr('src', rel);
          toast('ok', 'Picture swapped', 'The photo was copied into your site folder (' + rel + ').', 3200);
        }
      });
      // place right below the badge/actions, before the accordions
      box.insertBefore(btn, box.children[2] || null);
    }

    /* ── Matched CSS rules (edits reload — they affect the whole page) ── */
    if (el.rules && el.rules.length) {
      const acc = accordion('CSS Rules', false);
      const body = $('.acc-body', acc);
      for (const rule of el.rules.slice().reverse().slice(0, 6)) {
        const rbox = document.createElement('div');
        rbox.style.cssText = 'margin-top:10px;border:1px solid var(--stroke);border-radius:6px;overflow:hidden';
        const head = document.createElement('div');
        head.className = 'mono';
        head.style.cssText = 'font-size:11px;padding:6px 9px;background:var(--layer-alt);color:var(--accent-text);white-space:nowrap;overflow:hidden;text-overflow:ellipsis';
        head.textContent = rule.selector + (rule.media ? '  @' + rule.media : '');
        head.title = rule.selector;
        rbox.appendChild(head);
        const plist = document.createElement('div');
        plist.style.cssText = 'padding:4px 9px 8px';
        for (const [prop, val] of Object.entries(rule.props).slice(0, 12)) {
          const prow = document.createElement('div');
          prow.style.cssText = 'display:flex;gap:6px;align-items:center;margin-top:4px';
          const pl = document.createElement('span');
          pl.className = 'mono muted';
          pl.style.cssText = 'font-size:11px;min-width:96px;overflow:hidden;text-overflow:ellipsis';
          pl.textContent = prop;
          pl.title = prop;
          const pv = document.createElement('input');
          pv.type = 'text'; pv.spellcheck = false;
          pv.className = 'mono';
          pv.style.cssText = 'flex:1;font-size:11px;padding:3px 7px';
          pv.value = val;
          pv.addEventListener('change', () => {
            const singleSel = rule.selector.split(',')[0].trim();
            ChangeLog.note(filePath, `rule:${singleSel}:${prop}`, `Changed a style rule (${singleSel} → ${ChangeLog.propLabel(prop)}: ${pv.value})`);
            applyStructural(() => {
              const ok = Edits.setRuleProp(singleSel, prop, pv.value);
              if (!ok) { toast('warn', 'Rule not found in this file', 'It may come from an external stylesheet.'); return false; }
            });
          });
          prow.append(pl, pv);
          plist.appendChild(prow);
        }
        rbox.appendChild(plist);
        body.appendChild(rbox);
      }
      const note = document.createElement('p');
      note.className = 'muted';
      note.style.cssText = 'font-size:11px;margin:10px 2px 2px';
      note.textContent = 'These styles can affect other parts of the page too. Edits apply to <style> rules in this file.';
      body.appendChild(note);
      box.appendChild(acc);
    }
  }

  function normWeight(w) {
    if (w === 'normal') return '400';
    if (w === 'bold') return '700';
    return w || '';
  }
  function borderShorthand(styles) {
    const w = styles['border-width'], st = styles['border-style'], c = styles['border-color'];
    if (!st || st === 'none') return '';
    return [w, st, c].filter(Boolean).join(' ');
  }

  function startTextEdit(id) {
    Preview.select(id, false);
    setTimeout(() => {
      const ta = $('#propsContent textarea');
      if (ta) { ta.focus(); ta.select(); }
    }, 450);
  }

  return { show, clear, startTextEdit };
})();
